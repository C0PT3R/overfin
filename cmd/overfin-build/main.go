// Command overfin-build prepares an Overfin build with extra modules: it
// fetches each module and writes cmd/custom/main.go, the official build's
// main package plus them. The Dockerfile runs it when given MODULES:
//
//	docker build --build-arg MODULES="example.org/mymodule@v1.2.0" -t overfin .
//
// Each module is a Go package path, optionally with @version, whose package
// exports a Module type, like the official ones.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// official are the official build's modules, as cmd/overfin imports them.
var official = []string{
	"github.com/C0PT3R/overfin/modules/invites",
	"github.com/C0PT3R/overfin/modules/migration",
	"github.com/C0PT3R/overfin/modules/watchlist",
}

const self = "github.com/C0PT3R/overfin"

// spec is a module path with an optional version: nothing that could be
// read as anything but a path ends up in the generated source or the go
// command.
var spec = regexp.MustCompile(`^([a-z0-9][A-Za-z0-9._~-]*(?:/[A-Za-z0-9._~-]+)+)(?:@([A-Za-z0-9._+-]+))?$`)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "overfin-build:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) == 0 {
		return fmt.Errorf("no modules given")
	}
	src, err := generate(args)
	if err != nil {
		return err
	}
	for _, a := range args {
		m := spec.FindStringSubmatch(a)
		if strings.HasPrefix(m[1], self+"/") {
			continue // part of this repository
		}
		get := exec.Command("go", "get", a)
		get.Stdout, get.Stderr = os.Stdout, os.Stderr
		if err := get.Run(); err != nil {
			return fmt.Errorf("fetching %s: %w", a, err)
		}
	}
	if err := os.MkdirAll(filepath.Join("cmd", "custom"), 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join("cmd", "custom", "main.go"), src, 0o644)
}

// generate writes the main package: the official modules, then the given
// ones, each imported under its own name so their package names can't
// clash.
func generate(args []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by overfin-build. DO NOT EDIT.\n\n")
	b.WriteString("// Command custom is Overfin with the official modules and extra ones.\npackage main\n\nimport (\n")
	fmt.Fprintf(&b, "\t%q\n", self)
	paths := append([]string{}, official...)
	seen := map[string]bool{}
	for _, p := range official {
		seen[p] = true
	}
	for _, a := range args {
		m := spec.FindStringSubmatch(a)
		if m == nil {
			return nil, fmt.Errorf("%q isn't a module path (example.org/module, optionally @version)", a)
		}
		if seen[m[1]] {
			return nil, fmt.Errorf("%s is given twice, or is already an official module", m[1])
		}
		seen[m[1]] = true
		paths = append(paths, m[1])
	}
	for i, p := range paths {
		fmt.Fprintf(&b, "\tm%d %q\n", i, p)
	}
	b.WriteString(")\n\nfunc main() {\n\toverfin.Main(\n")
	for i := range paths {
		fmt.Fprintf(&b, "\t\tm%d.Module{},\n", i)
	}
	b.WriteString("\t)\n}\n")
	return format.Source(b.Bytes())
}
